        /// <summary>cos(fullAngleDegrees / 2) in Q30, clamped to 0..360 degrees.</summary>
        public static long CosHalfQ30(int fullAngleDegrees)
        {
            int index = fullAngleDegrees < 0 ? 0 : fullAngleDegrees > 360 ? 360 : fullAngleDegrees;
            return CosHalfTable[index];
        }

        /// <summary>
        ///     True when <paramref name="offset" /> lies within the cone around <paramref name="aim" /> whose half angle
        ///     has the cosine <paramref name="cosHalfQ30" />; a zero offset (the apex) is inside.
        /// </summary>
        public static bool Contains(FixedVec3 offset, FixedVec3 aim, long cosHalfQ30)
        {
            if (offset.IsZero)
            {
                return true;
            }

            long dot = FixedVec3.Dot(offset, aim);
            long lengths = LengthProduct(offset.LengthSquared, aim.LengthSquared);
            long limit = FixedMath.MulDiv(lengths, cosHalfQ30, UnitQ30);
            // WHY: one raw² of slack absorbs the integer square roots, like the float core's 1e-6 tolerance.
            return dot >= limit - 1L;
        }

        // WHY: |a|·|b| with 16 extra bits per square root while the squares are small enough, so short raw vectors
        // keep their precision.
        private static long LengthProduct(ulong aSquared, ulong bSquared)
        {
            ulong a = aSquared < (1UL << 31) ? FixedMath.SqrtFloor(aSquared << 32) : FixedMath.SqrtFloor(aSquared) << 16;
            ulong b = bSquared < (1UL << 31) ? FixedMath.SqrtFloor(bSquared << 32) : FixedMath.SqrtFloor(bSquared) << 16;
            long left = a > long.MaxValue ? long.MaxValue : (long)a;
            long right = b > long.MaxValue ? long.MaxValue : (long)b;
            return FixedMath.MulDiv(left, right, 1L << 32);
        }

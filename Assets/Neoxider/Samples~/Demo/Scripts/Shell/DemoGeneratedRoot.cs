using UnityEngine;

namespace Neo.Samples
{
    /// <summary>
    ///     Marks a scene object whose whole subtree is authored by a demo scene builder (the Neo.Demo.Editor
    ///     DemoSceneKit). Rebuilding the scene reconciles everything under it by name: missing objects are
    ///     created, existing ones are reused and objects the builder no longer produces are removed. Objects
    ///     outside generated roots are hand-authored and never touched. Has no runtime behaviour. Scenes of samples
    ///     that must not depend on this assembly (NeoxiderPages) use marker-less roots recognised by their reserved
    ///     "[Demo] " name instead.
    /// </summary>
    [AddComponentMenu("")]
    [DisallowMultipleComponent]
    public sealed class DemoGeneratedRoot : MonoBehaviour
    {
        [SerializeField] private string _key = string.Empty;
        [SerializeField] private string _builder = string.Empty;

        [SerializeField] [TextArea(2, 4)]
        private string _note = "Generated by a demo scene builder. Edits under this object are overwritten on rebuild.";

        /// <summary>Stable key the builder uses to find this root again (unique per scene).</summary>
        public string Key => _key;

        /// <summary>Builder method that last authored this root (informational).</summary>
        public string Builder => _builder;

        public string Note => _note;

        /// <summary>Records which builder owns this root. Called by the editor kit.</summary>
        public void Stamp(string key, string builder)
        {
            _key = key ?? string.Empty;
            _builder = builder ?? string.Empty;
            _note = "Generated by " + (string.IsNullOrEmpty(_builder) ? "a demo scene builder" : _builder) +
                    ". Edits under this object are overwritten on rebuild (Neoxider/Demo/Rebuild Active Demo Scene).";
        }
    }
}
